import os
import json
from reportlab.lib.pagesizes import letter
from reportlab.lib import colors
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle, HRFlowable
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
import openpyxl
from openpyxl.styles import Font, PatternFill, Alignment, Border, Side

def generate_pdf_report(scan_data, output_filepath):
    """Generates a sleek, professional PDF threat analysis report."""
    doc = SimpleDocTemplate(
        output_filepath,
        pagesize=letter,
        rightMargin=36, leftMargin=36, topMargin=36, bottomMargin=36
    )

    styles = getSampleStyleSheet()
    title_style = ParagraphStyle(
        'DocTitle',
        parent=styles['Heading1'],
        fontSize=22,
        textColor=colors.HexColor('#0f172a'),
        alignment=0,
        spaceAfter=10
    )
    subtitle_style = ParagraphStyle(
        'DocSub',
        parent=styles['Normal'],
        fontSize=10,
        textColor=colors.HexColor('#64748b'),
        spaceAfter=15
    )
    section_style = ParagraphStyle(
        'SectionHeading',
        parent=styles['Heading2'],
        fontSize=14,
        textColor=colors.HexColor('#0284c7'),
        spaceBefore=15,
        spaceAfter=8
    )
    body_style = ParagraphStyle(
        'BodyTextCustom',
        parent=styles['BodyText'],
        fontSize=10,
        textColor=colors.HexColor('#334155'),
        leading=14
    )

    story = []

    # Header
    story.append(Paragraph("🛡️ FakeShield AI — Digital Threat Analysis Report", title_style))
    story.append(Paragraph(f"Report ID: FS-SCAN-{scan_data.get('id', 'N/A')} | Generated: {scan_data.get('created_at', 'Now')}", subtitle_style))
    story.append(HRFlowable(width="100%", thickness=2, color=colors.HexColor('#0284c7'), spaceAfter=15))

    # Overview Table
    risk_score = scan_data.get('risk_score', 0)
    risk_level = scan_data.get('risk_level', 'UNKNOWN')

    if risk_level == 'HIGH':
        score_color = colors.HexColor('#ef4444')
    elif risk_level == 'MEDIUM':
        score_color = colors.HexColor('#f59e0b')
    elif risk_level == 'LOW':
        score_color = colors.HexColor('#eab308')
    else:
        score_color = colors.HexColor('#10b981')

    overview_data = [
        [Paragraph("<b>Scan Target Type:</b>", body_style), Paragraph(str(scan_data.get('scan_type', 'N/A')), body_style)],
        [Paragraph("<b>Risk Score:</b>", body_style), Paragraph(f"<font color='{score_color.hexval()}'><b>{risk_score} / 100 ({risk_level} RISK)</b></font>", body_style)],
        [Paragraph("<b>Threat Category:</b>", body_style), Paragraph(str(scan_data.get('threat_category', 'General')), body_style)],
        [Paragraph("<b>Input Target Data:</b>", body_style), Paragraph(str(scan_data.get('input_data', 'N/A'))[:120], body_style)],
    ]

    t = Table(overview_data, colWidths=[140, 380])
    t.setStyle(TableStyle([
        ('BACKGROUND', (0,0), (-1,-1), colors.HexColor('#f8fafc')),
        ('GRID', (0,0), (-1,-1), 0.5, colors.HexColor('#e2e8f0')),
        ('PADDING', (0,0), (-1,-1), 8),
    ]))
    story.append(t)
    story.append(Spacer(1, 15))

    # Detection Reasons (Explainable AI)
    story.append(Paragraph("🔍 Explainable AI (XAI) — Detection Reasons", section_style))
    explanations = scan_data.get('explanations', [])
    if isinstance(explanations, str) and explanations:
        try:
            explanations = json.loads(explanations)
        except Exception:
            explanations = [explanations]

    if explanations:
        for r in explanations:
            story.append(Paragraph(f"• {r}", body_style))
            story.append(Spacer(1, 4))
    else:
        story.append(Paragraph("No anomalous threat triggers were matched for this scan target.", body_style))

    story.append(Spacer(1, 15))

    # Multilingual Advice
    story.append(Paragraph("💡 Security Recommendations & Action Plan", section_style))
    story.append(Paragraph("<b>English:</b> Do not interact with unverified links or share sensitive credentials/OTPs.", body_style))
    story.append(Spacer(1, 4))
    story.append(Paragraph("<b>मराठी 🇮🇳:</b> संशयास्पद Link वर क्लिक करू नका व आपला OTP / Password कोणाशीही शेअर करू नका.", body_style))
    story.append(Spacer(1, 4))
    story.append(Paragraph("<b>हिंदी 🇮🇳:</b> अनधिकृत लिंक पर क्लिक न करें और अपना ओटीपी या पासवर्ड शेयर न करें।", body_style))

    story.append(Spacer(1, 25))
    story.append(HRFlowable(width="100%", thickness=1, color=colors.HexColor('#cbd5e1'), spaceAfter=10))
    story.append(Paragraph("Confidential Cybersecurity Report generated by FakeShield AI Autonomous Risk Engine.", subtitle_style))

    doc.build(story)
    return output_filepath

def generate_excel_history(scans_list, output_filepath):
    """Generates an Excel spreadsheet containing all scan history logs."""
    wb = openpyxl.Workbook()
    ws = wb.active
    ws.title = "FakeShield Scan History"

    # Headers
    headers = ["Scan ID", "User", "Scan Type", "Input Data", "Risk Score", "Risk Level", "Threat Category", "Date & Time"]
    ws.append(headers)

    header_fill = PatternFill(start_color="0F172A", end_color="0F172A", fill_type="solid")
    header_font = Font(name="Calibri", size=11, bold=True, color="FFFFFF")

    for col in range(1, len(headers) + 1):
        cell = ws.cell(row=1, column=col)
        cell.fill = header_fill
        cell.font = header_font
        cell.alignment = Alignment(horizontal="center", vertical="center")

    for scan in scans_list:
        row = [
            scan.get('id', 'N/A'),
            scan.get('username') or 'Guest',
            scan.get('scan_type', 'General'),
            str(scan.get('input_data', ''))[:80],
            scan.get('risk_score', 0),
            scan.get('risk_level', 'SAFE'),
            scan.get('threat_category', 'General'),
            str(scan.get('created_at', ''))
        ]
        ws.append(row)

    # Adjust column widths
    for col in ws.columns:
        max_len = max(len(str(cell.value or '')) for cell in col)
        col_letter = openpyxl.utils.get_column_letter(col[0].column)
        ws.column_dimensions[col_letter].width = max(max_len + 3, 12)

    wb.save(output_filepath)
    return output_filepath
